-- 021. SKU 없이도 로트가 존재할 수 있게
--
-- 사용자 확인(2026-08-18): **상품 등록 전에 먼저 발주하는 경우가 있다.**
-- 그때는 발주 시점에 바코드가 없고, 물건이 중국 창고에 도착한 뒤 쿠팡으로 보내기 전에
-- 상품을 등록하고 바코드를 발급받아 바코드 작업을 한다.
--
-- 그런데 지금까지는 `inventory_lots.sku_id`가 not null이라 **SKU가 붙어야만 로트가 생겼다.**
-- 그래서 이 경우 물건은 실제로 중국에 있는데 시스템엔 존재하지 않았다 —
-- 입고도 못 하고 재고에도 안 잡힌다(2026-08-18 사용자가 실제로 겪음).
--
-- 물건의 존재와 상품 등록은 **별개 사건**이다. 로트는 발주 시점에 태어나고,
-- SKU는 나중에 붙는다. 그래서 sku_id를 nullable로 바꾼다.
--
--   SKU 없는 로트로 할 수 있는 것   입고(도착 처리) · 불량 처리 · 중국창고 재고 확인
--   SKU가 있어야 하는 것            한국 출고 · 판매 원가(선입선출) · 재발주 제안
--                                   (바코드가 없으면 애초에 쿠팡에 못 보낸다)
-- ============================================================

alter table inventory_lots
  alter column sku_id drop not null;

comment on column inventory_lots.sku_id is
  'SKU가 아직 안 정해진 로트가 있을 수 있다(상품 등록 전에 발주한 경우). '
  '중국 창고까지는 SKU 없이 관리되고, 한국으로 출고하기 전에 반드시 채워져야 한다.';
