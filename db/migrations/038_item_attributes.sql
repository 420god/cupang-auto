-- 038. 옵션마다 필수속성 값을 담는다
--
-- 실측으로 알아낸 것(2026-08-21): **옵션명은 필수속성의 조합이다.**
--   itemName "감자색 70g 1개"  ↔  색상=감자색 · 개당 중량=70g · 수량=1개
-- WING 도 옵션 화면에서 `수량 [숫자] [개/박스/세트] [추가]` 로 옵션을 만들고,
-- 검색필터를 열면 "옵션을 먼저 설정해주세요" 라고 막는다.
--
-- 그동안은 옵션명만 받고 등록할 때 **추측으로** 속성을 채웠다
--   (색상 ← 옵션명, 무게 ← 우리가 잰 값).
-- 추측이 필요했던 이유는 값을 담을 자리가 없어서다. 이제 자리를 만든다.
--
-- 검색필터(선택 속성)는 상품 단위라 listing_projects.search_filters(037)에 있고,
-- 필수속성은 옵션마다 달라서 여기 둔다. 등록할 때 둘을 합쳐 items[].attributes 로 보낸다.
--
-- 모양: { "색상": "감자색", "개당 중량": "70g", "수량": "1개" }
-- 단위를 붙여서 담는다 — 실측 상품의 값이 그 형태였다.
-- ============================================================

alter table listing_project_items
  add column if not exists attributes jsonb not null default '{}'::jsonb;
