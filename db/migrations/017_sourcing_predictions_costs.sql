-- ============================================================
-- 017. 소싱 판단 기록 · 예측 원장 · 월 고정비
--
-- 왜 이 세 개가 한 파일인가: 전부 "복리로 개선되는 시스템"을 위한 것이라서다.
--
-- 사용자 목표(2026-08-18 명시): 소싱 → 상품 → 공급 → 판매 → 경영 → 에이전트가
-- 한 방향으로 흐르고 끝나는 게 아니라, 결과를 보고 **앞단의 판단 기준 자체를
-- 고쳐서** 다음 사이클이 더 나아지는 구조.
--
-- 그게 되려면 결과만 저장해선 안 되고 **판단 시점의 근거와 예측을 박제**해야 한다.
-- 대부분의 셀러 관리 시스템이 여기서 실패한다 — 매출·이익·재고는 다 기록하는데
-- "그때 뭘 기대했는지"가 없으니 틀렸는지조차 모르고, 데이터는 쌓이는데 아무것도
-- 배우지 못한다.
-- ============================================================

-- ── 소싱 후보 (조사한 것 전부. 버린 것도 남긴다) ─────────────
-- 버린 후보를 남기는 이유: 나중에 "내가 걸렀던 상품 중 남이 성공시킨 게 있나"를
-- 봐야 **거르는 기준**도 학습된다. 고른 것만 보면 골라진 것 안에서만 배운다.
create table if not exists sourcing_candidates (
  id                 uuid primary key default gen_random_uuid(),
  found_at           timestamptz not null default now(),
  method             text,      -- keyword_top | category_scan | competitor_track | manual | ...
  method_detail      text,      -- 실제 키워드/카테고리코드/추적대상 등

  -- 조사 대상 식별 (소싱 탭의 product_items와 느슨하게 연결 — 강한 FK는 안 건다.
  -- product_items는 수집 주기마다 갈아엎히는 성격이라 참조 무결성을 걸면 삭제가 막힌다)
  ref_product_id     bigint,
  ref_item_id        bigint,
  external_url       text,
  title              text,

  status             text not null default 'reviewing',  -- reviewing | promoted | rejected
  rejected_reason    text,
  memo               text,
  created_at         timestamptz not null default now()
);
create index if not exists sourcing_candidates_status on sourcing_candidates (status);

-- ── 소싱 판단 (승격 시점을 통째로 박제) ★ ────────────────────
-- 이 테이블의 존재 이유는 오직 하나: 6개월 뒤 "어떤 소싱 방법이 실제로 맞았나"를
-- 계산하기 위해서다. 그러려면 그때의 시장 스냅샷과 그때의 예상치가 같이 있어야 한다.
create table if not exists sourcing_decisions (
  id                    uuid primary key default gen_random_uuid(),
  candidate_id          uuid references sourcing_candidates(id),
  decided_at            timestamptz not null default now(),
  method                text,      -- 후보 발굴 경로 (성과 비교의 기준축)

  -- 판단 시점 시장 스냅샷 (나중에 절대 복원 불가 — 반드시 이때 찍어둔다)
  snapshot_seller_count int,
  snapshot_min_price    bigint,
  snapshot_avg_price    bigint,
  snapshot_review_count int,
  snapshot_commission_rate numeric,
  snapshot_raw          jsonb,

  -- 판단 시점 예상치 (실측과 대조할 상대. 이게 없으면 학습이 불가능하다) ★
  expected_monthly_qty  numeric,
  expected_unit_cost_krw numeric,
  expected_sell_price   bigint,
  expected_margin_rate  numeric,

  reason_tags           text[],    -- 승격 사유 태그(선택지)
  reason_memo           text,      -- 자유 메모 (나중에 AI가 읽을 원문)
  created_at            timestamptz not null default now()
);
create index if not exists sourcing_decisions_method on sourcing_decisions (method);

-- 015에서 자리만 뚫어둔 컬럼에 이제 FK를 건다
do $$
begin
  if not exists (
    select 1 from information_schema.table_constraints
    where constraint_name = 'my_skus_sourcing_decision_fk'
  ) then
    alter table my_skus
      add constraint my_skus_sourcing_decision_fk
      foreign key (sourcing_decision_id) references sourcing_decisions(id);
  end if;
end $$;

-- ── 예측 원장 (복리 루프의 심장) ★ ───────────────────────────
-- 시스템이 예측하는 지점 네 곳을 한 테이블에 모은다:
--   sourcing  예상 판매량·마진   → 90일 실적      → 소싱 기준 조정
--   reorder   예상 소진일·리드타임 → 실제           → 리드타임·안전재고 조정
--   price     예상 판매량         → 실제           → 가격 규칙 조정
--   ad        목표 ROAS          → 실제 ROAS      → 예산 배분 조정
--
-- 한 테이블에 모은 이유: "예측이 실제로 정확해지고 있는가"를 시스템 전체 단위로
-- 한 번에 볼 수 있어야 하고, 에이전트가 읽을 때도 여기 하나만 보면 되기 때문.
create table if not exists predictions (
  id               bigint generated by default as identity primary key,
  target_type      text not null,     -- sourcing | reorder | price | ad
  target_id        text,              -- 해당 도메인의 식별자 (po_id, decision_id 등)
  sku_id           uuid references my_skus(id),

  metric           text not null,     -- sales_qty | margin_rate | leadtime_days | roas | ...
  predicted_value  numeric not null,
  predicted_at     timestamptz not null default now(),
  basis            jsonb,             -- 예측 근거 원문 (어떤 값으로 어떻게 계산했나) ★
  model_version    text,              -- 규칙/공식 버전 — 규칙을 고쳤을 때 전후 비교용

  actual_value     numeric,
  measured_at      timestamptz,
  error            numeric generated always as (actual_value - predicted_value) stored,

  created_at       timestamptz not null default now()
);
create index if not exists predictions_type_metric on predictions (target_type, metric);
create index if not exists predictions_sku on predictions (sku_id);
create index if not exists predictions_open on predictions (target_type) where measured_at is null;

-- ── 월 고정비 ────────────────────────────────────────────────
-- 사용자 결정(2026-08-18): 상품별로 배분하지 않는다. 월 전체 손익에서만 뺀다.
-- 배분은 임의성이 커서 SKU 단위 판단을 오히려 왜곡한다.
create table if not exists fixed_costs_monthly (
  id          bigint generated by default as identity primary key,
  year_month  text not null,          -- 'YYYY-MM'
  item_name   text not null,          -- 사무실 / 프로그램 구독 / 인건비 ...
  amount_krw  bigint not null,
  memo        text,
  created_at  timestamptz not null default now()
);
create unique index if not exists fixed_costs_monthly_uniq
  on fixed_costs_monthly (year_month, item_name);

-- ── 알림 (텔레그램 발송 대상 큐 겸 이력) ─────────────────────
-- 카톡이 아니라 텔레그램으로 정한 이유: 카톡 자동화는 계정 정지 위험과 토큰 갱신
-- 부담이 크다(2026-08-18 사용자 동의).
create table if not exists alerts (
  id            bigint generated by default as identity primary key,
  type          text not null,   -- stockout_risk | margin_drop | deposit_mismatch
                                 -- | cost_unconfirmed | competitor_entry | ...
  severity      text not null default 'info',  -- info | warn | critical
  sku_id        uuid references my_skus(id),
  title         text not null,
  body          text,
  context       jsonb,
  sent_at       timestamptz,     -- 텔레그램 발송 시각 (NULL이면 미발송)
  resolved_at   timestamptz,
  created_at    timestamptz not null default now()
);
create index if not exists alerts_unsent on alerts (created_at) where sent_at is null;
create index if not exists alerts_open on alerts (type) where resolved_at is null;

do $$
declare t text;
begin
  foreach t in array array['sourcing_candidates','sourcing_decisions','predictions',
                           'fixed_costs_monthly','alerts']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "read_for_authenticated" on %I', t);
    execute format('create policy "read_for_authenticated" on %I for select to authenticated using (true)', t);
    execute format('drop policy if exists "write_for_admin" on %I', t);
    execute format('create policy "write_for_admin" on %I for all to authenticated using (is_admin()) with check (is_admin())', t);
  end loop;
end $$;
